// fakeEC is an in-memory imitation of the Endpoint Central custom group API
// and the Zoho token endpoint, built from the documented request/response
// examples in the OpenAPI spec.
type fakeEC struct {
	t      *testing.T
	mu     sync.Mutex
	nextID int64
	groups map[int64]*fakeGroup
	// knownResources are the resource IDs that exist; others are reported
	// back as invalidResourceIds.
	knownResources map[int64]string
	tokenCalls     int
	groupUpdates   int
	server         *httptest.Server

	// patch state (fakeserver_dcapi_test.go, fakeserver_apd_test.go)
	apdTasks  map[int64]*fakeAPDTask
	policies  []map[string]any
	nextAPDID int64
	// apdModifies counts modifyAPDTask calls.
	apdModifies int
	// mdm is the MDM API on its own host (fakeserver_mdm_test.go).
	mdm *fakeMDM
}

type fakeGroup struct {
	ID              int64
	Name            string
	Type            int
	Category        int
	Description     string
	Members         []int64
	CriteriaList    []map[string]any
	CriteriaPattern string
}

const fakeToken = "1000.fake-access-token"

func newFakeEC(t *testing.T) *fakeEC {
	f := &fakeEC{
		t:              t,
		nextID:         300,
		groups:         map[int64]*fakeGroup{},
		knownResources: map[int64]string{101: "SRV-DC01", 102: "SRV-APP01", 103: "SRV-FILE01", 104: "WS-01"},
	}
	mux := http.NewServeMux()
	mux.HandleFunc("POST /oauth/v2/token", f.token)
	mux.HandleFunc("GET /api/1.4/customgroup/getCGList", f.auth(f.list))
	mux.HandleFunc("GET /api/1.4/customgroup/getCGDetails", f.auth(f.details))
	mux.HandleFunc("POST /api/1.4/customgroup/addCg", f.auth(f.add))
	mux.HandleFunc("POST /api/1.4/customgroup/updateCg", f.auth(f.update))
	mux.HandleFunc("POST /api/1.4/customgroup/deleteCg", f.auth(f.delete))
	f.registerDCAPI(mux)
	f.mdm = newFakeMDM(f)
	f.server = httptest.NewServer(mux)
	t.Cleanup(f.server.Close)
	return f
}

func (f *fakeEC) URL() string { return f.server.URL }

func writeJSON(w http.ResponseWriter, status int, v any) {
	w.Header().Set("Content-Type", "application/json")
	w.WriteHeader(status)
	_ = json.NewEncoder(w).Encode(v)
}

func legacyError(w http.ResponseWriter, status int, msgType, code, desc string) {
	writeJSON(w, status, map[string]any{
		"message_type": msgType, "message_version": "1.4", "status": "error",
		"error_code": code, "error_description": desc,
	})
}

func legacyOK(w http.ResponseWriter, msgType string, payload map[string]any) {
	writeJSON(w, http.StatusOK, map[string]any{
		"message_type": msgType, "message_version": "1.4", "status": "success",
		"message_response": payload,
	})
}

func (f *fakeEC) token(w http.ResponseWriter, r *http.Request) {
	_ = r.ParseForm()
	f.mu.Lock()
	f.tokenCalls++
	f.mu.Unlock()
	if r.Form.Get("grant_type") != "refresh_token" || r.Form.Get("refresh_token") != "good-refresh" {
		// Zoho reports bad credentials with HTTP 200 and an error field.
		writeJSON(w, http.StatusOK, map[string]any{"error": "invalid_code"})
		return
	}
	writeJSON(w, http.StatusOK, map[string]any{
		"access_token": fakeToken, "expires_in": 3600, "token_type": "Bearer", "api_domain": f.server.URL,
	})
}

func (f *fakeEC) auth(next http.HandlerFunc) http.HandlerFunc {
	return func(w http.ResponseWriter, r *http.Request) {
		if r.Header.Get("Authorization") != "Zoho-oauthtoken "+fakeToken {
			writeJSON(w, http.StatusUnauthorized, map[string]any{"status": "error", "error_code": "10002", "error_description": "invalid oauth token"})
			return
		}
		f.mu.Lock()
		defer f.mu.Unlock()
		next(w, r)
	}
}

func categoryName(c int) string {
	switch c {
	case 2:
		return "Dynamic"
	case 5:
		return "Static Unique"
	default:
		return "Static"
	}
}

func typeName(t int) string {
	if t == 2 {
		return "Users"
	}
	return "Computers"
}

func (g *fakeGroup) summary() map[string]any {
	return map[string]any{
		"group_id": g.ID, "group_name": g.Name, "group_category": categoryName(g.Category),
		"group_type": typeName(g.Type), "domain_name": "CORP",
		"group_created_on": 1710325600000, "group_modified_on": 1710412000000,
	}
}

// autoGroup is a built-in, auto-generated group, listed only on request.
var autoGroup = &fakeGroup{ID: 1, Name: "All Mac machines", Type: 1, Category: 2,
	CriteriaList: []map[string]any{{"columnId": 7, "comparator": "equal", "logicalOperator": "AND", "criteriaValue": []string{"Mac"}}}, CriteriaPattern: "1"}

func (f *fakeEC) list(w http.ResponseWriter, r *http.Request) {
	ids := make([]int64, 0, len(f.groups))
	for id := range f.groups {
		ids = append(ids, id)
	}
	sort.Slice(ids, func(i, j int) bool { return ids[i] < ids[j] })
	out := []map[string]any{}
	if r.URL.Query().Get("isAutoGeneratedCGNeeded") == "true" {
		out = append(out, autoGroup.summary())
	}
	for _, id := range ids {
		out = append(out, f.groups[id].summary())
	}
	legacyOK(w, "getCGList", map[string]any{"getcglist": map[string]any{
		"operation_status": "success",
		"response":         map[string]any{"result": map[string]any{"cg_list": out}},
	}})
}

func (f *fakeEC) details(w http.ResponseWriter, r *http.Request) {
	name := r.URL.Query().Get("cgName")
	all := []*fakeGroup{autoGroup}
	for _, g := range f.groups {
		all = append(all, g)
	}
	for _, g := range all {
		if g.Name != name {
			continue
		}
		res := g.summary()
		if g.Category == 2 {
			res["criteriaList"] = g.CriteriaList
			res["criteriaPattern"] = g.CriteriaPattern
		} else {
			members := []map[string]any{}
			for _, m := range g.Members {
				members = append(members, map[string]any{"resourceId": strconv.FormatInt(m, 10), "name": f.knownResources[m], "domainName": "CORP"})
			}
			res["groupMembers"] = members
		}
		legacyOK(w, "getCGDetails", map[string]any{"getcgdetails": map[string]any{
			"operation_status": "success",
			"response":         map[string]any{"result": res, "message": "Operation has been completed successfully"},
		}})
		return
	}
	legacyError(w, http.StatusOK, "getCGDetails", "20015", name+" does not exist")
}

type fakeWriteBody struct {
	GroupID         *int64           `json:"groupId"`
	GroupName       string           `json:"groupName"`
	GroupType       json.RawMessage  `json:"groupType"`
	GroupCategory   json.RawMessage  `json:"groupCategory"`
	Description     *string          `json:"description"`
	ResourceIDs     *[]int64         `json:"resourceIds"`
	CriteriaList    []map[string]any `json:"criteriaList"`
	CriteriaPattern string           `json:"criteriaPattern"`
}

// splitMembers separates known resource IDs from unknown ones, mimicking the
// API's partial-success behaviour.
func (f *fakeEC) splitMembers(ids []int64) (valid, invalid []int64) {
	for _, id := range ids {
		if _, ok := f.knownResources[id]; ok {
			valid = append(valid, id)
		} else {
			invalid = append(invalid, id)
		}
	}
	return
}

func normalizeCriteria(in []map[string]any) []map[string]any {
	out := make([]map[string]any, len(in))
	for i, c := range in {
		cp := map[string]any{}
		for k, v := range c {
			cp[k] = v
		}
		cp["columnName"] = fmt.Sprintf("COL_%v", c["columnId"])
		cp["I18NComparator"] = c["comparator"]
		out[i] = cp
	}
	return out
}

func (f *fakeEC) add(w http.ResponseWriter, r *http.Request) {
	var b fakeWriteBody
	if err := json.NewDecoder(r.Body).Decode(&b); err != nil {
		legacyError(w, http.StatusBadRequest, "addCg", "70501", "bad json")
		return
	}
	gt, _ := strconv.Atoi(strings.Trim(string(b.GroupType), `"`))
	gc, _ := strconv.Atoi(strings.Trim(string(b.GroupCategory), `"`))
	if b.GroupName == "" || gt == 0 || gc == 0 {
		legacyError(w, http.StatusPreconditionFailed, "addCg", "70501", "Required parameters are missing to create/update Custom Group.")
		return
	}
	for _, g := range f.groups {
		if g.Name == b.GroupName {
			legacyError(w, http.StatusPreconditionFailed, "addCg", "70502", "Custom group name is already in use.")
			return
		}
	}
	f.nextID++
	g := &fakeGroup{ID: f.nextID, Name: b.GroupName, Type: gt, Category: gc}
	if b.Description != nil {
		g.Description = *b.Description
	}
	resp := map[string]any{"groupName": g.Name, "groupType": strconv.Itoa(gt), "groupCategory": strconv.Itoa(gc), "cgResourceId": strconv.FormatInt(g.ID, 10)}
	if gc == 2 {
		if len(b.CriteriaList) == 0 || b.CriteriaPattern == "" {
			legacyError(w, http.StatusPreconditionFailed, "addCg", "70503", "Given criteria pattern is null.")
			return
		}
		g.CriteriaList = normalizeCriteria(b.CriteriaList)
		g.CriteriaPattern = b.CriteriaPattern
	} else {
		if b.ResourceIDs == nil {
			legacyError(w, http.StatusPreconditionFailed, "addCg", "70501", "Required parameters are missing to create/update Custom Group.")
			return
		}
		valid, invalid := f.splitMembers(*b.ResourceIDs)
		g.Members = valid
		if len(invalid) > 0 {
			resp["invalidResourceIds"] = invalid
		}
	}
	f.groups[g.ID] = g
	legacyOK(w, "addCg", map[string]any{"addcg": resp})
}

func (f *fakeEC) update(w http.ResponseWriter, r *http.Request) {
	var b fakeWriteBody
	if err := json.NewDecoder(r.Body).Decode(&b); err != nil || b.GroupID == nil {
		legacyError(w, http.StatusPreconditionFailed, "updateCg", "70501", "Required parameters are missing to create/update Custom Group.")
		return
	}
	if len(b.GroupType) > 0 || len(b.GroupCategory) > 0 {
		legacyError(w, http.StatusPreconditionFailed, "updateCg", "70501", "groupType and groupCategory are immutable")
		return
	}
	g, ok := f.groups[*b.GroupID]
	if !ok {
		legacyError(w, http.StatusNotFound, "updateCg", "70506", "No such Custom Group found.")
		return
	}
	f.groupUpdates++
	resp := map[string]any{"groupName": b.GroupName, "cgResourceId": strconv.FormatInt(g.ID, 10)}
	if b.GroupName != "" {
		g.Name = b.GroupName
	}
	// Absent fields keep their value; the API documents them as optional.
	if b.Description != nil {
		g.Description = *b.Description
	}
	if g.Category == 2 {
		if len(b.CriteriaList) == 0 {
			legacyError(w, http.StatusPreconditionFailed, "updateCg", "70501", "Required parameters are missing to create/update Custom Group.")
			return
		}
		g.CriteriaList = normalizeCriteria(b.CriteriaList)
		if b.CriteriaPattern != "" {
			g.CriteriaPattern = b.CriteriaPattern
		}
	} else {
		if b.ResourceIDs == nil {
			legacyError(w, http.StatusPreconditionFailed, "updateCg", "70501", "Required parameters are missing to create/update Custom Group.")
			return
		}
		valid, invalid := f.splitMembers(*b.ResourceIDs)
		g.Members = valid
		if len(invalid) > 0 {
			resp["invalidResourceIds"] = invalid
		}
	}
	legacyOK(w, "updateCg", map[string]any{"updatecg": resp})
}

func (f *fakeEC) delete(w http.ResponseWriter, r *http.Request) {
	id, _ := strconv.ParseInt(r.URL.Query().Get("cgId"), 10, 64)
	g, ok := f.groups[id]
	if !ok {
		legacyError(w, http.StatusNotFound, "deleteCg", "70506", "No such Custom Group found.")
		return
	}
	delete(f.groups, id)
	legacyOK(w, "deleteCg", map[string]any{"deletecg": map[string]any{"message": g.Name + " was successfully deleted!"}})
}

// groupByName is a test helper (callers must not hold f.mu).
func (f *fakeEC) groupByName(name string) *fakeGroup {
	f.mu.Lock()
	defer f.mu.Unlock()
	for _, g := range f.groups {
		if g.Name == name {
			cp := *g
			return &cp
		}
	}
	return nil
}

// setMembers changes a group's members as if done in the console.
func (f *fakeEC) setMembers(name string, ids ...int64) {
	f.mu.Lock()
	defer f.mu.Unlock()
	for _, g := range f.groups {
		if g.Name == name {
			g.Members = ids
			return
		}
	}
	f.t.Fatalf("setMembers: no group %q", name)
}
